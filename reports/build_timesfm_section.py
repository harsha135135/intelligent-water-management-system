            "study chooses a model for a production campus system, so the checkpoint that could be "
            "deployed is the one evaluated.",
            f"* **Configuration.** Zero-shot — no training, no fine-tuning; target series only, no "
            f"covariates; context {man['context']:,} hours truncated at each origin, as for "
            f"Chronos-2; point forecast = the median, the statistic Chronos-2's point forecast "
