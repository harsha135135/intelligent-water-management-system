"""Write §17 of ``docs/review_summary.md`` - the TimesFM comparison - from the result files.

Every number in the section is read here, at build time, from the files the benchmark writes, and
the section is replaced in place between its two marker comments. Nothing in it is typed by hand,
so it cannot drift from the data: change a result, rerun the pipeline, rerun this.

    python reports/build_timesfm_section.py      # ~5 s → docs/review_summary.md §17

Reads:
    results/chronos2/timesfm_manifest.json           checkpoint, config, device, timing, audits
    results/chronos2/metrics_by_horizon.csv          macro metrics, every model (metrics.py)
    results/chronos2/timesfm_comparison.csv          TimesFM vs Chronos-2 / NPTS / SeasonalNaive
    results/chronos2/timesfm_per_tank.csv            TimesFM vs Chronos-2, per tank
    results/chronos2/unified/significance_vs_all.csv Chronos-2 vs TimesFM, bootstrap + DM
    results/chronos2/unified/significance_timesfm.csv  TimesFM vs every non-foundation model
    results/chronos2/unified/leaderboard.csv         rank, coverage, width, volume bias
    results/chronos2/unified/zero_inflation_h24.csv  tail miss rates at 1 d
    results/chronos2/unified/cost.csv                wall clocks, incl. the same-CPU pair
    results/chronos2/calibrated/{summary,calibration_effect,daily_campus}.csv  45-day view
"""

from __future__ import annotations

import json
import pathlib
import re
